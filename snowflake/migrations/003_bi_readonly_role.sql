-- 003 (K-13): read-only BI role for Superset. It can read the GOLD schema and nothing else.
-- BI queries run on their own XS warehouse so TeksOptima sees BI cost separately from dbt.

CREATE ROLE IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER COMMENT = 'Superset: SELECT on DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOLD only';

CREATE WAREHOUSE IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_XS
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    STATEMENT_TIMEOUT_IN_SECONDS = 300
    COMMENT = 'daily-expense-tracker-fintech-application BI (Superset), XS, 60s auto-suspend';

ALTER WAREHOUSE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_XS SET TAG
    DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE.PROJECT = 'daily-expense-tracker-fintech-application',
    DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE.ENVIRONMENT = 'dev',
    DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE.COST_CENTER = 'engineering';

GRANT USAGE ON WAREHOUSE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_XS TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER;
GRANT USAGE ON DATABASE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER;
GRANT USAGE ON SCHEMA DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOLD TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOLD TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOLD TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOLD TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOLD TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER;

-- Service user for Superset: key-pair only. An admin sets the public key out of band:
--   ALTER USER DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_SUPERSET SET RSA_PUBLIC_KEY = '<public key>';
CREATE USER IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_SUPERSET
    TYPE = SERVICE
    DEFAULT_ROLE = DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER
    DEFAULT_WAREHOUSE = DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_XS
    COMMENT = 'Superset service user (read-only BI)';
GRANT ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_BI_READER TO USER DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_SUPERSET;
