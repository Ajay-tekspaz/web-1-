-- 001: right-sized analytics warehouse for daily-expense-tracker-fintech-application, tagged for cost attribution, with a cost guard.
-- Idempotent. Apply with: python snowflake/apply_migrations.py --apply   (dry run without --apply)
-- Run as the migration role (SNOWFLAKE_MIGRATION_ROLE), which may create roles, users, warehouses and tags
-- in the dev account; the resource monitor needs ACCOUNTADMIN. dbt, the loaders and Airflow run as
-- DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE, which may not.

CREATE DATABASE IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV;
CREATE SCHEMA IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE;

-- Object tags (Snowflake tags must exist before they are set on an object)
CREATE TAG IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE.PROJECT
    COMMENT = 'Project that owns the object, for chargeback';
CREATE TAG IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE.ENVIRONMENT
    ALLOWED_VALUES 'dev', 'staging', 'prod'
    COMMENT = 'Deployment environment';
CREATE TAG IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE.COST_CENTER
    COMMENT = 'Cost center for chargeback';

-- The pipeline's role: works only inside this database (grants here and in 002)
CREATE ROLE IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE COMMENT = 'daily-expense-tracker-fintech-application dev: load raw data, run dbt and the forecast';
GRANT ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE TO ROLE SYSADMIN;

-- Cost guard: notify at 80%, suspend the warehouse at 100% of 10 credits a month
CREATE RESOURCE MONITOR IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_MONITOR
    WITH CREDIT_QUOTA = 10
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS ON 80 PERCENT DO NOTIFY
             ON 100 PERCENT DO SUSPEND;

-- XS = 1 credit/hour; suspend after 60 s idle
CREATE WAREHOUSE IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_XS
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    STATEMENT_TIMEOUT_IN_SECONDS = 1800
    STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 300
    RESOURCE_MONITOR = DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_MONITOR
    COMMENT = 'daily-expense-tracker-fintech-application dbt + loaders (XS, 60s auto-suspend)';

-- Enforce the settings even if the warehouse already existed with different ones
ALTER WAREHOUSE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_XS SET
    WAREHOUSE_SIZE = XSMALL
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    RESOURCE_MONITOR = DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_MONITOR;

ALTER WAREHOUSE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_XS SET TAG
    DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE.PROJECT = 'daily-expense-tracker-fintech-application',
    DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE.ENVIRONMENT = 'dev',
    DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOVERNANCE.COST_CENTER = 'engineering';

GRANT USAGE ON WAREHOUSE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_XS TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE;

-- Check: expect size X-Small, auto_suspend 60, resource_monitor DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_MONITOR
SHOW WAREHOUSES LIKE 'DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_XS';
