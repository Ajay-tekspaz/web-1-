-- 002: schemas the pipeline writes to, granted to the DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE role.
--   DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_SANDBOX  raw tables (Airbyte or the Python loader)
--   STAGING      dbt staging views
--   GOLD         dbt marts + forecast (the only schema BI can read, see 003)
--   ML           forecast script output

CREATE SCHEMA IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_SANDBOX;
CREATE SCHEMA IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.STAGING;
CREATE SCHEMA IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOLD;
CREATE SCHEMA IF NOT EXISTS DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.ML;

GRANT USAGE ON DATABASE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE;
GRANT ALL ON SCHEMA DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_SANDBOX TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE;
GRANT ALL ON SCHEMA DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.STAGING TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE;
GRANT ALL ON SCHEMA DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.GOLD TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE;
GRANT ALL ON SCHEMA DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_DEV.ML TO ROLE DAILY_EXPENSE_TRACKER_FINTECH_APPLICATION_PIPELINE_ROLE;
